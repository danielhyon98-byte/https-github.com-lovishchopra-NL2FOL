"""The translator's public API for attached components (``docs/PUBLIC_API.md``).

The overseer is a separate sub-project (``overseer/``, package ``epinoic_overseer``). It re-derives what the translator
decided on every journaled transfer, so it needs the translator's own deterministic code: the engine, the channel's
rules, the parsers' readings, the STEM front end. It reaches that code ONLY through the modules of this package (and the
integration protocol, :mod:`epinoic_logic.integration`); it never imports a translator module directly, and the
translator never imports the overseer (it is attached through ``RouterHub(auditor=...)`` and the overseer port).

Public modules, one per area: :mod:`~epinoic_logic.api.ir`, :mod:`~epinoic_logic.api.engine`,
:mod:`~epinoic_logic.api.channel`, :mod:`~epinoic_logic.api.integrity`, :mod:`~epinoic_logic.api.translate`,
:mod:`~epinoic_logic.api.adapters`, :mod:`~epinoic_logic.api.branches`, :mod:`~epinoic_logic.api.stem` and
:mod:`~epinoic_logic.api.named`. Each maps its public names to the internal implementation (``EXPORTS``) and resolves a
name when it is imported, so the API adds no copy of any behaviour: the overseer runs exactly the translator's code.

The contract: a name listed here keeps its meaning across translator releases of the same minor version; removing or
changing one is a breaking change, recorded in ``docs/PUBLIC_API.md`` and by :data:`API_VERSION`; the overseer states
the names and the MAJOR version it needs in ``epinoic_overseer.compat`` (``REQUIRED_API``, ``API_MAJOR``) and checks them
when it is imported. The list is generated into ``docs/PUBLIC_API.md`` by ``python -m epinoic_logic.api --markdown`` (a
test compares the two).

Versions of the API (:data:`API_VERSION`, stated since 1.1): 1.0 is the API as it stood before the architecture review
after arena round 8, which stated no version; 1.1 adds 26 names the overseer's tests and harness still imported from the
translator's internal modules (architecture review after arena round 8: ``SourceRef``, ``Assertion``, ``IntConst``,
``RealConst``, ``Limits`` and ``ALLOWED_OPS`` in ``ir``; ``LedgerEntry``, ``SynthesizedClaim``, ``ConflictRecord``,
``ROLE_CONTRACTS`` and ``at_stated_precision`` in ``integrity``; ``EligibilityClass``, ``EligibilityDecision``,
``ProviderInfo`` and ``StructuralFinding`` in ``translate``; ``ConstraintResult``, ``CoverageRecord``, ``answer_parts``
and ``count_answer_words`` in ``channel``; ``BranchRegistry``, ``FormalCheck``, ``SubjectBranch`` and ``EnglishPack`` in
``branches``; ``truncate_claim_text`` in ``adapters``; ``clear_document_cache`` in ``stem``; ``DEFINITIVE`` in ``engine``),
removing or changing none.
"""
from __future__ import annotations

AREAS: tuple[str, ...] = ("ir", "engine", "channel", "integrity", "translate", "adapters", "branches", "stem", "named")

#: The public API's version, MAJOR.MINOR: MINOR goes up with every name added; MAJOR with every name removed or
#: changed in meaning. Attached components check it (the overseer: ``epinoic_overseer.compat``, which refuses at import
#: a translator whose API states another MAJOR than the one it was built against).
API_VERSION = "1.1"

__all__ = ["API_VERSION", "AREAS", "exports_table", "markdown"]


def exports_table() -> dict[str, dict[str, tuple[str, str | None]]]:
    """{area: {public name: (internal module, attribute)}} for every public module."""
    import importlib
    return {a: dict(importlib.import_module(f"{__name__}.{a}").EXPORTS) for a in AREAS}


def markdown() -> str:
    """``docs/PUBLIC_API.md``: every public name with the internal name it resolves to."""
    out = [
        "# The translator's public API for attached components",
        "",
        "GENERATED by `python -m epinoic_logic.api --markdown` from `src/epinoic_logic/api/` (a test compares the two). Do",
        "not edit by hand.",
        "",
        f"API version: {API_VERSION} (`epinoic_logic.api.API_VERSION`, MAJOR.MINOR: MINOR goes up with every name added, MAJOR",
        "with every name removed or changed in meaning; the overseer states the MAJOR it needs in `epinoic_overseer.compat`).",
        "",
        "The overseer (`overseer/`, package `epinoic_overseer`) is a separate sub-project. It depends on the translator only",
        "through these modules and the integration protocol (`epinoic_logic.integration`, `integration/PROTOCOL.md`); the",
        "translator never imports it (it is attached through `RouterHub(auditor=...)` and the overseer port,",
        "`EPINOIC_OVERSEER_PORT`). Each public name resolves, when it is imported, to the internal module and attribute listed",
        "beside it: the API adds no copy of any behaviour, so the overseer re-derives every decision with exactly the",
        "translator's code. A name that is private inside the translator has a public name here. Removing or changing a name",
        "is a breaking change for the overseer; the overseer's own suite imports every name it uses through this API.",
        "",
    ]
    for area, table in exports_table().items():
        out += [f"## `epinoic_logic.api.{area}` ({len(table)} names)", "", "| public name | internal module | internal name |", "|---|---|---|"]
        for public in sorted(table):
            mod, attr = table[public]
            out.append(f"| `{public}` | `{mod}` | {'(the module itself)' if attr is None else '`' + attr + '`'} |")
        out.append("")
    return "\n".join(out)
